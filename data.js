const INDEX = [];
for (const [dept, words] of Object.entries(STEMS)) {
  for (const w of words.split(/\s+/)) if (w) INDEX.push([w, dept]);
}
// Длинные основы проверяем раньше коротких: «масло сливочное» → молочное, а не бакалея
INDEX.sort((a, b) => b[0].length - a[0].length);

export const norm = (s) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9 %,.]/g, ' ').replace(/\s+/g, ' ').trim();

export function guessDept(name) {
  const words = norm(name).split(' ');
  for (const [stem, dept] of INDEX) {
    const s = stem.replace(/ё/g, 'е');
    if (words.some((w) => w.startsWith(s))) return dept;
  }
  return 'other';
}

